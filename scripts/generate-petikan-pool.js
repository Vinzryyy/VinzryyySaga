/* global process */
/**
 * generate-petikan-pool.js
 *
 * Auto-generate Buah Muda card pool untuk Petikan dari /public/archive/.
 * Pick 40 frames evenly-spaced dari ~364 unique frames available,
 * generate kartu metadata (id, title, caption, image) deterministically.
 *
 * Output: src/data/petikanMudaPool.js — committed ke git (mirror
 * pattern galleryData.js).
 *
 * Re-run setiap kali archive di-refresh atau caption pool di-update.
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const ROOT = path.join(__dirname, '..');
const ARCHIVE_DIR = path.join(ROOT, 'public', 'archive');
const OUTPUT_FILE = path.join(ROOT, 'src', 'data', 'petikanMudaPool.js');

const TARGET_COUNT = 40;

// Caption pool — poetic, observational, Indonesian. Cycled deterministic
// per index biar consistent across re-runs.
const CAPTIONS_POOL = [
  'Satu frame kecil dari panggung yang terjaga.',
  'Momen biasa, disimpan di arsip yang sabar.',
  'Sapaan singkat dari hari yang lain.',
  'Sudut yang sering tak terlihat, tapi ada.',
  'Kenangan yang melintas pelan.',
  'Cahaya jatuh di tempat yang tepat.',
  'Detik yang kebetulan kena lensa.',
  'Senyum sederhana di tengah lampu sorot.',
  'Hari yang biasa, tapi terasa hangat.',
  'Frame yang menunggu ditemui kembali.',
  'Suara samar di belakang panggung.',
  'Langkah kecil yang menjadi catatan.',
  'Senja yang turun di balik panggung.',
  'Gerak yang lembut, lensa yang sabar.',
  'Bayang yang lebih panjang dari aslinya.',
  'Wajah yang sedang mendengarkan.',
  'Tangan yang melambai pelan.',
  'Mata yang sedang menatap jauh.',
  'Tawa yang terdengar di lorong.',
  'Detik yang seharusnya hilang, tapi tidak.',
  'Lampu panggung yang akrab.',
  'Sudut backstage yang jarang dibagikan.',
  'Gerakan kecil yang sering dilewatkan.',
  'Pose tenang di antara dua lagu.',
  'Pertukaran pandang yang singkat.',
  'Catatan kecil di sela rutinitas.',
  'Foto yang seperti kebetulan, padahal sengaja.',
  'Adegan biasa yang tetap dirawat.',
  'Frame yang umur-nya pendek tapi diingat.',
  'Layar yang menangkap nafas.',
];

const TITLES_POOL = [
  'Frame',
  'Snapshot',
  'Ingatan',
  'Sudut',
  'Sapaan',
  'Kenangan',
  'Detik',
  'Bayangan',
  'Cahaya',
  'Gerak',
];

function main() {
  if (!fs.existsSync(ARCHIVE_DIR)) {
    console.error('Archive dir tidak ditemukan:', ARCHIVE_DIR);
    process.exit(1);
  }

  const all = fs
    .readdirSync(ARCHIVE_DIR)
    .filter((f) => /^img-\d+\.webp$/.test(f))
    .sort((a, b) => {
      const na = parseInt(a.match(/(\d+)/)[1], 10);
      const nb = parseInt(b.match(/(\d+)/)[1], 10);
      return na - nb;
    });

  if (all.length === 0) {
    console.error('Tidak ada img-*.webp di archive');
    process.exit(1);
  }

  console.log(`Found ${all.length} frames di archive.`);

  // Pick deterministically evenly-spaced — bukan random biar regenerate
  // produces same output (idempotent build).
  const step = Math.max(1, Math.floor(all.length / TARGET_COUNT));
  const picked = [];
  for (let i = 0; i < TARGET_COUNT && i * step < all.length; i++) {
    picked.push(all[i * step]);
  }

  const cards = picked.map((file, idx) => {
    const num = file.match(/(\d+)/)[1];
    const titlePrefix = TITLES_POOL[idx % TITLES_POOL.length];
    return {
      id: `muda-img-${num}`,
      tier: 'muda',
      title: `${titlePrefix} · #${num}`,
      caption: CAPTIONS_POOL[idx % CAPTIONS_POOL.length],
      image: `/archive/${file}`,
    };
  });

  const content = `/**
 * Auto-generated by scripts/generate-petikan-pool.js
 * ${cards.length} Buah Muda cards di-pick evenly-spaced dari archive/.
 *
 * Do not edit by hand. Re-run \`npm run generate-petikan-pool\` to refresh.
 */

export const PETIKAN_MUDA_POOL = ${JSON.stringify(cards, null, 2)};
`;

  fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true });
  fs.writeFileSync(OUTPUT_FILE, content);
  console.log(`Wrote ${cards.length} cards → ${path.relative(ROOT, OUTPUT_FILE)}`);
}

main();
