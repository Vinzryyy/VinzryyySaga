/**
 * Build the photo pool for the Memory Match mini game.
 *
 * Reads the gallery archive, keeps photos that have a 400px thumbnail
 * (built by scripts/build-thumbnails.js) and are not excluded from the
 * gallery, then computes a 64-bit dHash per thumbnail so the game can avoid
 * putting near-identical shots (burst photos) on the same board.
 *
 * Output: public/data/memory-pool.json
 *
 * Run: npm run build-memory-pool   (re-run after importing new photos)
 */

import sharp from 'sharp';
import { readFile, writeFile, stat } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { GALLERY_IMAGES } from '../src/data/galleryData.js';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const PUBLIC = path.join(ROOT, 'public');
const OUT = path.join(PUBLIC, 'data', 'memory-pool.json');

const exists = async (p) => {
  try {
    await stat(p);
    return true;
  } catch {
    return false;
  }
};

/** 9x8 grayscale difference hash → 16 hex chars. */
const dHash = async (file) => {
  const px = await sharp(file).grayscale().resize(9, 8, { fit: 'fill' }).raw().toBuffer();
  let bits = '';
  for (let y = 0; y < 8; y++) {
    for (let x = 0; x < 8; x++) bits += px[y * 9 + x] > px[y * 9 + x + 1] ? '1' : '0';
  }
  return BigInt(`0b${bits}`).toString(16).padStart(16, '0');
};

const cleanEvent = (s) => {
  if (!s) return null;
  const one = s.split('\n')[0].replace(/\s+/g, ' ').trim();
  return one.length > 80 ? `${one.slice(0, 77)}…` : one;
};

const main = async () => {
  const enrich = JSON.parse(await readFile(path.join(PUBLIC, 'data', 'gallery-enrichments.json'), 'utf8'));
  const byKey = enrich.byMediaKey || {};
  const excluded = new Set(enrich.excludeMediaKeys || []);

  const items = [];
  const seen = new Set();
  for (const img of GALLERY_IMAGES) {
    const m = (img.url || '').match(/^\/archive\/x\/x-([A-Za-z0-9_-]+)\.[a-z]+$/);
    if (!m) continue;
    const key = m[1];
    if (excluded.has(key) || seen.has(key)) continue;
    const webp = `/archive/x/thumbs/x-${key}.webp`;
    const avif = `/archive/x/thumbs/x-${key}.avif`;
    const webpFile = path.join(PUBLIC, webp);
    if (!(await exists(webpFile))) continue;
    seen.add(key);
    const e = byKey[key] || {};
    items.push({
      id: key,
      webp,
      avif: (await exists(path.join(PUBLIC, avif))) ? avif : null,
      date: e.eventDate || img.date || null,
      year: img.year || null,
      event: cleanEvent(e.eventName),
      h: await dHash(webpFile),
    });
  }

  items.sort((a, b) => (b.date || '').localeCompare(a.date || '') || a.id.localeCompare(b.id));
  const doc = {
    _readme: 'Generated by scripts/build-memory-pool.js. Do not edit by hand.',
    generatedAt: new Date().toISOString(),
    count: items.length,
    items,
  };
  await writeFile(OUT, `${JSON.stringify(doc)}\n`);
  console.log(`memory-pool.json: ${items.length} photos`);
};

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
